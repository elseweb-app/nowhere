// Key transfer envelope, per SPEC.md §15: moves an Ed25519 seed between a user's
// devices without ever touching a relay. Nothing here talks to a network — a private
// key must never be transmitted to any server, encrypted or not — and this file is
// grepped by a test to make sure it stays that way.
//
// A photographed QR is an offline attack with unlimited time and no rate limit, so the
// envelope's `expires_at` defends against a stale QR being reused, not against
// cracking. Entropy in the transfer code is the only thing defending a captured
// envelope, which is why the code is generated by the client and never chosen by the
// user, and why it travels separately from the QR rather than inside it.

import { randomBytes, toHex, fromHex } from './crypto.js'

const subtle = globalThis.crypto.subtle

const KDF_NAME = 'PBKDF2-HMAC-SHA256'
const KDF_ITERATIONS = 600000
const CIPHER_NAME = 'AES-256-GCM'
const SALT_BYTES = 16
const IV_BYTES = 12

const TRANSFER_CODE_BYTES = 8
export const TRANSFER_CODE_ENTROPY_BITS = TRANSFER_CODE_BYTES * 8

export function generateTransferCode() {
  return toHex(randomBytes(TRANSFER_CODE_BYTES))
}

async function deriveAesKey(code, salt, iterations, keyUsages) {
  const codeKeyMaterial = await subtle.importKey(
    'raw',
    new TextEncoder().encode(code),
    { name: 'PBKDF2' },
    false,
    ['deriveKey']
  )
  return subtle.deriveKey(
    { name: 'PBKDF2', hash: 'SHA-256', salt, iterations },
    codeKeyMaterial,
    { name: 'AES-GCM', length: 256 },
    false,
    keyUsages
  )
}

export async function wrapKey({ seed, code, expiresAt }) {
  const salt = randomBytes(SALT_BYTES)
  const iv = randomBytes(IV_BYTES)
  const key = await deriveAesKey(code, salt, KDF_ITERATIONS, ['encrypt'])
  const ciphertext = await subtle.encrypt({ name: 'AES-GCM', iv }, key, fromHex(seed))

  return {
    v: 1,
    type: 'key-transfer',
    kdf: { name: KDF_NAME, salt: toHex(salt), iterations: KDF_ITERATIONS },
    cipher: { name: CIPHER_NAME, iv: toHex(iv) },
    ciphertext: toHex(new Uint8Array(ciphertext)),
    expires_at: expiresAt,
  }
}

export async function unwrapKey({ envelope, code, now }) {
  // Exclusive at the boundary, matching how the rest of this package treats expiry.
  if (now >= envelope.expires_at) {
    throw new Error('key transfer envelope has expired')
  }

  // The envelope declares its own KDF parameters (iterations included) rather than
  // this module assuming its own constant, which is what lets a second implementation
  // — one that raised its default iteration count later, say — still decrypt it.
  const salt = fromHex(envelope.kdf.salt)
  const iv = fromHex(envelope.cipher.iv)
  const key = await deriveAesKey(code, salt, envelope.kdf.iterations, ['decrypt'])

  let plaintext
  try {
    plaintext = await subtle.decrypt({ name: 'AES-GCM', iv }, key, fromHex(envelope.ciphertext))
  } catch {
    // AES-GCM's tag check fails the same way for a wrong code and for a tampered
    // ciphertext — that ambiguity is the point, since a relay-side observer must not
    // be able to distinguish the two from anything the envelope carries.
    throw new Error('key transfer code is wrong, or the envelope was tampered with')
  }

  return toHex(new Uint8Array(plaintext))
}
